/*
 * primaryFixed / primaryFixedDim / onPrimaryFixed / onPrimaryFixedVariant, and the same four
 * each for secondary and tertiary.
 *
 * These exist so a surface can hold the SAME colour in light and dark — a split pane or a
 * side-by-side layout where one half must not flip with the theme. This app has no such surface:
 * every screen is single-scheme and the AMOLED variant is a deliberate full flip, so these are
 * UNUSED BY APP UI.
 *
 * They are populated rather than left to the library because that is what the Fixed contract
 * means: each resolves to its LIGHT-scheme counterpart in both themes, so a stock component that
 * asks for one renders correctly and legibly — it simply never appears in this app's own screens.
 *
 * The spec gives primaryFixedDim (#A8CFC3) as the worked example. The secondary and tertiary Dim
 * values below are derived by applying that same per-channel ratio to their own containers
 * (R x0.81, G x0.89, B x0.88), so they are traceable to a stated decision rather than picked by
 * eye. If the spec ever names them explicitly, replace these and delete this paragraph.
 */

