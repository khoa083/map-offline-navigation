/**
 * "Cartography Teal" — the v2 reskin color system, seeded from #0B4F45.
 *
 * Two independent palettes, not one derived from the other:
 *  - Light: standard M3 surface roles on a warm off-white ground (#F7F5EC), for daytime /
 *    outdoor use. The outdoor-legibility floor for this app is 4.5:1 for any text and 3:1 for
 *    any icon or control edge, checked against each token's paired on-color — do not add a
 *    pair below that floor.
 *  - Amoled: background is a *real* #000000 so unlit OLED pixels stay off at night, not a "dim
 *    of light" the way a conventional Material dark theme reads (a raised dark grey base).
 *    #101614 is the first raised container, never the background.
 *
 * Values are hand-authored to match the design spec (Offline Map M3 Expressive Spec, sheets 1a
 * and 1b) rather than generated by the M3 theme builder from a single seed — re-check contrast
 * against the spec before regenerating any of this.
 *
 * ## Every role in ColorScheme has a value here, on purpose
 *
 * Material 3's ColorScheme has 48 roles. An earlier revision of this file defined roughly half
 * and aliased or omitted the rest. That is not a saving: a stock M3 component *will* ask for
 * `tertiaryContainer` or `inverseSurface` eventually, and a role left to the library default
 * answers with Baseline purple in the middle of a teal app. Roles this app does not use in its
 * own screens are still given an in-palette value, and are marked "unused by app UI" so the
 * distinction between "not used" and "not defined" stays visible.
 */

